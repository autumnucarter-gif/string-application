package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
        // What is my favorite color?
        String favColor = "Red";
        System.out.println("My favorite color is " + favColor);

        // Year you started this class?
        int yuuStart = 2026;
        System.out.println("I started this class in " + yuuStart);

        // What is my middle initial?
        char middleInitial = 'U';
        System.out.println("My middle initial is " + middleInitial);

        // Do you have any pets?
        boolean hasPets = false;
        System.out.println("Do I have any pets? " + hasPets);

        // Nice message
        String niceMessage = "I hope you've had a SPECTACULAR day so far!!";
        System.out.println("Hello!, " + niceMessage);

        // How many days in one week?
        int dayWeek = 7;
        System.out.println("There are " + dayWeek + "in a week.");

        // Price of coffee
        double coffeePrice = 7.99;
        System.out.println("Coffee today cost " + coffeePrice);

        // My favorite lettet?
        char favLetter = 'A';
        System.out.println("My favorite letter is " + favLetter);

        // Is it raining?
        boolean isRaining = false;
        System.out.println("Is is raining? " + isRaining);

    }
}